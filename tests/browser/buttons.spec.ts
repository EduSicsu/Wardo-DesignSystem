import { test, expect } from '@playwright/test';
import AxeBuilder from '@axe-core/playwright';

test('default tertiary app button retains its neutral fill, artwork and native activation', async ({page}, testInfo) => {
  const errors:string[]=[];
  page.on('pageerror',error=>errors.push(error.message));
  page.on('console',message=>{if(message.type()==='error')errors.push(message.text());});
  await page.goto('/buttons');
  await expect(page).toHaveTitle('Wardo — Component library');
  await expect(page.getByRole('heading',{name:'App button examples'})).toBeVisible();
  const example=page.getByRole('region',{name:'tertiary button example'});
  const button=example.getByRole('button',{name:'Button',exact:true});
  const icon=button.locator('[data-artwork-icon="button-plus"]');
  const label=button.locator('span').last();
  const colors=()=>button.evaluate(el=>({background:getComputedStyle(el).backgroundColor,color:getComputedStyle(el).color}));
  await expect.poll(colors).toEqual({background:'rgb(22, 22, 21)',color:'rgb(255, 253, 252)'});
  const bounds=await button.boundingBox();
  expect(bounds!.height).toBe(48);expect(bounds!.width).toBeCloseTo(130,0);
  expect((await icon.boundingBox())!.width).toBe(20);expect((await icon.boundingBox())!.height).toBe(20);
  expect(await icon.evaluate(el=>getComputedStyle(el).maskImage)).not.toBe('none');
  expect((await icon.boundingBox())!.x).toBeLessThan((await label.boundingBox())!.x);
  await example.screenshot({path:`/tmp/wardo-tertiary-button-${testInfo.project.name}-light.png`});
  await button.focus();await page.keyboard.press('Enter');
  await expect(page.getByRole('status')).toHaveText('tertiary action activated');
  await expect(button).toBeFocused();
  expect(await button.evaluate(el=>getComputedStyle(el).outlineStyle)).toBe('solid');
  await page.getByRole('checkbox',{name:'Right-to-left buttons'}).check();
  expect((await icon.boundingBox())!.x).toBeGreaterThan((await label.boundingBox())!.x);
  await page.getByLabel('Button theme').selectOption('wardo-dark');
  await page.mouse.move(0,0);
  await expect.poll(colors).toEqual({background:'rgb(255, 253, 252)',color:'rgb(43, 41, 38)'});
  await example.screenshot({path:`/tmp/wardo-tertiary-button-${testInfo.project.name}-dark-rtl.png`});
  expect((await new AxeBuilder({page}).include('main').withTags(['wcag2a','wcag2aa','wcag21aa']).analyze()).violations).toEqual([]);
  await page.getByRole('checkbox',{name:'Disable buttons'}).check();
  await expect(button).toBeDisabled();
  await expect.poll(colors).toEqual({background:'rgba(255, 255, 255, 0.12)',color:'rgba(255, 255, 255, 0.38)'});
  await button.click({force:true});
  await expect(page.getByRole('status')).toHaveText('tertiary action activated');
  await page.getByRole('checkbox',{name:'Disable buttons'}).uncheck();
  await expect(button).toBeEnabled();
  await expect.poll(colors).toEqual({background:'rgb(255, 253, 252)',color:'rgb(43, 41, 38)'});
  await page.evaluate(()=>{document.documentElement.style.fontSize='200%';});
  await expect(button).toBeVisible();
  expect((await button.boundingBox())!.height).toBeGreaterThan(48);
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true);
  await example.screenshot({path:`/tmp/wardo-tertiary-button-${testInfo.project.name}-scaled.png`});
  expect(errors).toEqual([]);
});
